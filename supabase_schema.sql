-- 1. Tabla de Programas de Postgrado
CREATE TABLE IF NOT EXISTS public.programas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    tipo TEXT NOT NULL,
    descripcion TEXT,
    duracion TEXT,
    modalidad TEXT DEFAULT 'Presencial',
    pensum JSONB,
    activo INTEGER DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT timezone('utc', now())
);

-- 2. Tabla de Preinscripciones de Aspirantes
CREATE TABLE IF NOT EXISTS public.preinscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_solicitud TEXT UNIQUE NOT NULL,
    cedula TEXT NOT NULL,
    nombres TEXT NOT NULL,
    apellidos TEXT NOT NULL,
    fecha_nacimiento TEXT,
    genero TEXT,
    email TEXT NOT NULL,
    telefono TEXT NOT NULL,
    direccion TEXT,
    ciudad TEXT,
    estado TEXT,
    universidad_egreso TEXT,
    titulo_obtenido TEXT,
    anio_egreso INTEGER,
    programa_id BIGINT NOT NULL REFERENCES public.programas(id) ON DELETE RESTRICT,
    motivacion TEXT,
    estado_solicitud TEXT DEFAULT 'pendiente',
    fecha_registro TIMESTAMPTZ DEFAULT timezone('utc', now()),
    fecha_actualizacion TIMESTAMPTZ DEFAULT timezone('utc', now()),
    correo_enviado INTEGER DEFAULT 0
);

-- 3. Índices para Alto Rendimiento
CREATE INDEX IF NOT EXISTS idx_preinscripciones_codigo ON public.preinscripciones(codigo_solicitud);
CREATE INDEX IF NOT EXISTS idx_preinscripciones_cedula ON public.preinscripciones(cedula);
CREATE INDEX IF NOT EXISTS idx_preinscripciones_email ON public.preinscripciones(email);
CREATE INDEX IF NOT EXISTS idx_preinscripciones_programa ON public.preinscripciones(programa_id);
CREATE INDEX IF NOT EXISTS idx_preinscripciones_estado ON public.preinscripciones(estado_solicitud);
CREATE INDEX IF NOT EXISTS idx_programas_activo ON public.programas(activo);

-- 4. Seguridad a Nivel de Fila (Row Level Security - RLS)
ALTER TABLE public.programas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.preinscripciones ENABLE ROW LEVEL SECURITY;

-- Políticas permisivas para la API del backend (clave anon o service_role)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'programas' AND policyname = 'Lectura pública de programas'
    ) THEN
        CREATE POLICY "Lectura pública de programas" ON public.programas
            FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'preinscripciones' AND policyname = 'Permitir lectura de preinscripciones'
    ) THEN
        CREATE POLICY "Permitir lectura de preinscripciones" ON public.preinscripciones
            FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'preinscripciones' AND policyname = 'Permitir inserción de preinscripciones'
    ) THEN
        CREATE POLICY "Permitir inserción de preinscripciones" ON public.preinscripciones
            FOR INSERT WITH CHECK (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'preinscripciones' AND policyname = 'Permitir actualización de preinscripciones'
    ) THEN
        CREATE POLICY "Permitir actualización de preinscripciones" ON public.preinscripciones
            FOR UPDATE USING (true);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE tablename = 'preinscripciones' AND policyname = 'Permitir eliminación de preinscripciones'
    ) THEN
        CREATE POLICY "Permitir eliminación de preinscripciones" ON public.preinscripciones
            FOR DELETE USING (true);
    END IF;
END $$;

